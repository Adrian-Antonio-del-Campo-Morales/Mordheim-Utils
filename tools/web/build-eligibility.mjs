/** Deterministic desktop bundle of the same eligibility module the browser imports. */
import { build } from "esbuild";
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
const root = new URL("../../", import.meta.url);
const entry = new URL("packages/typescript/domain/eligibility/bridge.ts", root);
const target = new URL("packages/python/roster-construction/mordheim_construction/_eligibility.js", root);
const hash = createHash("sha256");
for (const name of ["index.ts", "bridge.ts"]) hash.update((await readFile(new URL(name, entry), "utf8")).replaceAll("\r\n", "\n"));
const digest = hash.digest("hex");
const result = await build({ absWorkingDir: fileURLToPath(root), entryPoints: [fileURLToPath(entry)], bundle: true, write: false,
  format: "iife", globalName: "MordheimEligibility", target: "es2022", platform: "neutral", charset: "utf8",
  banner: { js: `// Generated by tools/web/build-eligibility.mjs. Do not edit.\n// Source SHA256: ${digest}` },
});
const output = result.outputFiles[0].text;
if (process.argv.includes("--check")) {
  const existing = await readFile(target, "utf8").catch(() => "");
  if (existing !== output) throw new Error("Shared eligibility bundle is stale. Run npm run build:eligibility.");
  console.log("Shared eligibility bundle is current.");
} else {
  await writeFile(target, output, "utf8");
  console.log("Built shared eligibility bundle.");
}
