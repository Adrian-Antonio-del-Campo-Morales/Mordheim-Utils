/** DOM feedback may only repeat an exact message owned by this catalogue. */
export function uiMessageForText(text: unknown): UiMessage | undefined {
  if (typeof text !== "string") return undefined;
  for (const key of Object.keys(messages) as (keyof typeof messages)[]) {
    if (messages[key].es === text || messages[key].en === text) return { key };
  }
  return undefined;
}
